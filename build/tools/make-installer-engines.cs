// Writes the engine list of the installer's engine page (installer/Filee.iss includes the result): package ids, their
// components, sizes and which ones are suggested come from EngineDownloads (engines.json), names and texts from the
// app's translations. So the installer offers exactly what Settings → Engines offers, in the same words.
// Run by build/build-installer.ps1:  dotnet run build/tools/make-installer-engines.cs -- <output .iss>
#:project ../../src/Filee.Engines/Filee.Engines.csproj
#:property PublishAot=false

using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Filee.Engines.Infrastructure;

if (args.Length != 1)
{
    Console.Error.WriteLine("usage: dotnet run build/tools/make-installer-engines.cs -- <output .iss>");
    return 2;
}

var repo = Environment.CurrentDirectory;
while (!File.Exists(Path.Combine(repo, "Filee.slnx")))
    repo = Path.GetDirectoryName(repo) ?? throw new InvalidOperationException("Run this from inside the Filee repository.");

// [Languages] names in installer/Filee.iss → the app's translation files.
(string Inno, string App)[] languages = [("en", "en"), ("ko", "ko"), ("zhcn", "zh-CN")];
var texts = languages.ToDictionary(l => l.Inno, l => Load(Path.Combine(repo, "src", "Filee.App", "Assets", "i18n", l.App + ".json")));

// The file is included in the middle of [Code], where a ";" line would be Pascal: open a section first.
var iss = new StringBuilder()
    .AppendLine("[CustomMessages]")
    .AppendLine("; Generated by build/tools/make-installer-engines.cs (build/build-installer.ps1 runs it). Do not edit.");

void Message(string name, string key)
{
    foreach (var (inno, _) in languages)
        iss.AppendLine($"{inno}.{name}={ToInnoMessage(texts[inno][key])}");
}

Message("EnginesTitle", "setup.title");
Message("EnginesDescription", "setup.description");
Message("EnginesNote", "setup.note");
Message("EngineSizes", "engines.package.size");
Message("EngineInstalled", "engines.state.installed");
Message("TaskStartup", "general.start_with_system");
Message("TaskContextMenu", "general.context_menu");
foreach (var package in EngineDownloads.Packages)
    Message("Engine_" + package.Id, $"engines.package.{package.Id}.name");

iss.AppendLine()
    .AppendLine("[Code]")
    .AppendLine("procedure AddEngines;")
    .AppendLine("begin");
foreach (var package in EngineDownloads.Packages)
{
    // EngineInstaller marks each component's folder under the engines root; LibreOffice extensions ("oxt") sit
    // inside LibreOffice and come with it, so they are not checked separately.
    var markerFolders = package.Components.Where(c => EngineDownloads.Components[c].Kind != "oxt");
    iss.AppendLine(string.Create(CultureInfo.InvariantCulture,
        $"  AddEngine('{package.Id}', '{string.Join(',', markerFolders)}', '{FormatBytes(EngineDownloads.DownloadSize(package))}', " +
        $"'{FormatBytes(package.InstalledSize)}', {(EngineDownloads.IsSuggested(package) ? "True" : "False")});"));
}
iss.AppendLine("end;");

var output = Path.GetFullPath(args[0]);
Directory.CreateDirectory(Path.GetDirectoryName(output)!);
// Inno Setup reads scripts as UTF-8 only when they start with a BOM.
File.WriteAllText(output, iss.ToString(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: true));
Console.WriteLine($"{EngineDownloads.Packages.Count} engine packages -> {output}");
return 0;

static Dictionary<string, string> Load(string path)
{
    using var json = JsonDocument.Parse(File.ReadAllText(path, Encoding.UTF8));
    return json.RootElement.EnumerateObject().ToDictionary(p => p.Name, p => p.Value.GetString() ?? "");
}

// One line; the app's {0} placeholders become Inno Setup's %1. A literal % would need %% in formatted messages only,
// so it is simply not allowed.
static string ToInnoMessage(string text)
{
    if (text.Contains('%'))
        throw new InvalidOperationException($"'%' is not supported in installer texts: {text}");
    return Regex.Replace(text, @"\{(\d)\}", m => "%" + (int.Parse(m.Groups[1].Value, CultureInfo.InvariantCulture) + 1))
        .ReplaceLineEndings("%n");
}

// Same rounding as EnginePackageState.FormatBytes in the app ("422 MB", "1.3 GB").
static string FormatBytes(long bytes) => bytes >= 1_000_000_000
    ? string.Create(CultureInfo.InvariantCulture, $"{bytes / 1_000_000_000.0:0.0} GB")
    : string.Create(CultureInfo.InvariantCulture, $"{Math.Max(1, bytes / 1_000_000)} MB");
